// 「元に戻す」を付けられる操作の共通の形（純粋な型と規則。I/O は持たない）。
//
// 世の中の標準どおり、**やり直しの履歴は持たない**。直前の1件だけをトーストの
// ボタンで戻せる（Gmail・Material の snackbar、iOS の「取り消す」と同じ）。
// アプリ全体の undo スタックは、どこまで戻るのかが利用者にも作る側にも見えなく
// なるので作らない。
//
// **戻し方は「逆操作」ではなく「復元」にする。** 逆向きに同じ操作をやり直すと、
// 操作のたびに落ちる情報を拾えない。実例: 予定を別の日へ動かすと、乗継当日の
// 選択（どの乗継の出発側/到着側か）はその日に紐づくので捨てられる。逆向きに
// 動かし直しても選択は戻らない。動かす前の値を丸ごと控えておいて書き戻せば戻る。
//
// この形に載せられない操作には「元に戻す」を付けない（＝確認を挟む方に倒す）。
// 判断の分かれ目は docs/ui-guidelines.md「確認の要否は『復旧コスト』で決める」。

import type { Result } from "./data/result";

// `T` は「控え」（memento）の型。**やる側が控えを作り、戻す側がそれを受け取る。**
// 呼び出し側で変数に溜めて閉じ込める形にすると、控え忘れや取り違えが起きる
// （消す前の姿は消した瞬間にしか手に入らないので、その受け渡しを型で縛る）。
// 控えが要らない操作（動かす等、元の値が手元にあるもの）は T = void。
export type Undoable<T = void> = {
  // やること。戻すのに要る控えを返す。
  apply: () => Promise<Result<T>>;
  // やる前の状態に戻すこと。**逆操作ではなく、控えておいた値の書き戻し。**
  restore: (memento: T) => Promise<Result<void>>;
  // 成功した時にトーストに出す文言（「予定を移動しました」）。
  done: string;
  // 失敗した時にトーストに出す文言。
  failed: (error: string) => string;
  // **画面から先に消す/戻す。** サーバの往復と再取得を待ってから消すと、
  // 消えるまでの間ずっと空の行が残る（実機フィードバック: 取り込みの下書きで
  // 数百 ms、費用でも遅れが見えた。行が高いものほど目立つ）。結果は分かって
  // いるので、押した瞬間に見た目を先に合わせ、あとから実データで揃える。
  //
  // 対で渡す。**hide を渡した時は、成功しても再取得を「元に戻す」の間だけ
  // 待つ**（消した行を手元に残しておけば、戻すのも待たせずに済む）。
  // 失敗したら show して元に戻す。
  hide?: () => void;
  show?: () => void;
};
