// 処理中インジケータを出し始めるまでの待ち時間（ms）。
//
// ほとんどの操作はこれより速く終わり、その場合は何も出さない。一瞬だけ出て
// 消える表示は、出さない場合より「遅い」と感じさせるため（規約は
// docs/ui-guidelines.md の「処理中（ローディング）」）。
//
// 300ms は「操作が自分の行為の結果だと感じられる上限」として広く使われている値。
// これを web と RN で共有し、プラットフォームごとに数字が散らないようにする。
export const BUSY_INDICATOR_DELAY_MS = 300;

// インジケータを一度出したら、最低これだけは出し続ける（ms）。
// 閾値を少し超えただけの処理で、出た瞬間に消える点滅を防ぐ。
export const BUSY_INDICATOR_MIN_VISIBLE_MS = 300;
