// トーストが画面に出ている時間（ms）。web と RN で同じ数字を使う。
//
// **Material Design が幅で決めている**（最短4秒・最長10秒）ので、その帯の中から
// 「そのトーストが何を求めるか」で選ぶ。読むだけのものは短い側、押させるものは
// 長い側。同じ部品なので揃えたくなるが、求めていることが違う以上、消えるまでの
// 間も違ってよい——読むのは一目でも、押すのは「気付く→読む→決める→指を運ぶ」の
// 4手が要る。
//
// アクセシビリティ側（WCAG 2.2.1 Timing Adjustable）は、操作を持つ表示が勝手に
// 消えることを問題として扱い、止められること・十分長いことを求める。web は
// ホバーとフォーカスで止まる（Base UI Toast の既定）が、**触る画面にホバーは
// 無い**ので、長さで担保するしかない。
//
// 規約は docs/ui-guidelines.md の「フィードバック」。
export const TOAST_MS = 5000;
export const TOAST_WITH_ACTION_MS = 10000;
