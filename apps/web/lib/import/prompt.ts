// 候補旅行のヒント（id・旅行名・日程）。割り当て推論に使う。
export type TripHint = {
  id: string;
  title: string;
  startDate: string | null;
  endDate: string | null;
};

// 件名＋本文（＋候補旅行）から、抽出対象のユーザメッセージを組み立てる。
export function buildImportPrompt(input: {
  subject: string;
  text: string;
  trips?: TripHint[];
}): string {
  const subject = input.subject.trim();
  const text = input.text.trim();
  const trips = input.trips ?? [];
  const tripLines = trips.length
    ? trips
        .map(
          (t) =>
            `- id=${t.id}: ${t.title}（${t.startDate ?? "?"}〜${t.endDate ?? "?"}）`,
        )
        .join("\n")
    : "(候補なし)";
  return [
    "次のメールから費用と予定を抽出してください。",
    "",
    `件名: ${subject || "(なし)"}`,
    "",
    "本文:",
    text,
    "",
    "候補の旅行（このメールがどれに属するか tripId で答える。該当無し/不明は null）:",
    tripLines,
  ].join("\n");
}
