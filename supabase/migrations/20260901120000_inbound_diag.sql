-- 取り込みの診断メモ。**後から原因を追うための列**。
--
-- 取り込みは他の機能と違って追いにくい。理由は3つ:
--   一度きりで再実行できない（本文は処理後に消す設計）
--   結果が毎回同じとは限らない（LLM が入る）
--   ユーザーが見ていない間にサーバーで非同期に走る
-- 他の機能は DB の今の状態が答えで、同じ操作をやり直せば再現するので、この列は要らない。
--
-- Vercel のログでは代わりにならない。実測すると保持されているのは直近の数十行だけで、
-- 数時間前の取り込みのログはもう残っていない（「今起きている問題を追う」用）。
--
-- 中身は**長さ・ホスト名・件数・真偽値だけ**。本文・URL・金額は入れない。
--   {"plain":217,"html":7827,"used":"html",
--    "enrich":{"host":"...","adopted":false},
--    "merge":{"candidates":8,"merged":true}}
--
-- 寿命は最大90日。未確定のまま放置された行は expire-inbound が90日で消し、
-- 確定/破棄したものは raw / body_text と同時にその場で消す
-- （20260901130000_clear_diag_on_finalize.sql）。確定した行は90日の削除対象から
-- 外れるので、そこで消さないと無期限に残ってしまう。
-- 大きさは1行あたり数百バイト。月の上限2000通 × 90日でも 2MB 弱で、同じ行の
-- body_text（平均2.8KB）の方がはるかに重い。
--
-- インデックスは張らない（件数が少なく、絞り込みは既存の列で足りる）。
-- 読み出しは列を明示している経路しかないので、アプリの通信量には乗らない。
alter table public.inbound_emails add column if not exists diag jsonb;

comment on column public.inbound_emails.diag is
  '取り込みの診断メモ（長さ・ホスト名・件数・真偽値のみ。本文/URL/金額は入れない）';
